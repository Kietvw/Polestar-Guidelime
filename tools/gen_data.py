"""Write !Polestar_Guidelime/Data.lua: zone names, flight points and inns from Polestar's data.

    python tools/gen_data.py [--addons DIR]

DIR is a folder holding the Polestar addon (default: $POLESTAR_ADDONS, else
the folder above this repository). Rerun after a Polestar update.
"""
import argparse
import os
import re

REPO = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
OUT = os.path.join(REPO, "!Polestar_Guidelime", "Data.lua")


def read_travel(path):
    text = open(path, encoding="utf-8").read()
    zones = {int(m.group(1)): m.group(2)
             for m in re.finditer(r'\[(\d+)\] = \{ name = "([^"]+)", c = (\d+)', text)}
    taxi = []
    block = text[text.index("taxi = {"):text.index("flights = {")]
    for m in re.finditer(r'\{(\d+),(\d+),(-?[\d.]+),(-?[\d.]+),(\d+),(-?[\d.]+),(-?[\d.]+),(\d+),"([^"]+)"', block):
        taxi.append({"node": int(m.group(1)), "map": int(m.group(5)), "x": float(m.group(6)),
                     "y": float(m.group(7)), "mask": int(m.group(8)), "name": m.group(9)})
    inns = []
    block = text[text.index("inns = {"):]
    for m in re.finditer(r'\{area=(\d+),c=\d+,f="(\w)",map=(\d+),names=\{([^}]*)\},npc=(\d+),wx=[^,]+,wy=[^,]+,x=([\d.]+),y=([\d.]+)\}', block):
        inns.append({"area": int(m.group(1)), "frame": m.group(2), "map": int(m.group(3)),
                     "names": re.findall(r'"([^"]+)"', m.group(4)), "npc": int(m.group(5)),
                     "x": float(m.group(6)), "y": float(m.group(7))})
    return zones, taxi, inns


def q(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--addons", default=os.environ.get("POLESTAR_ADDONS") or os.path.dirname(REPO),
                    help="folder holding the Polestar addon")
    args = ap.parse_args()
    polestar = os.path.join(args.addons, "Polestar")
    zones, taxi, inns = read_travel(os.path.join(polestar, "Nav", "TravelData.lua"))
    for line in open(os.path.join(polestar, "Maps", "ZoneLevels.lua"), encoding="utf-8"):
        m = re.search(r"\[(\d+)\] = \{[^}]*\},\s*--\s*(.+?)\s*$", line)
        if m:
            zones.setdefault(int(m.group(1)), m.group(2))
    version = "?"
    toc = os.path.join(polestar, "Polestar.toc")
    if os.path.exists(toc):
        m = re.search(r"^## Version:\s*(\S+)", open(toc, encoding="utf-8").read(), re.M)
        version = m.group(1) if m else version

    lines = [
        f"-- Generated by tools/gen_data.py from Polestar {version}'s Nav/TravelData.lua and Maps/ZoneLevels.lua",
        "-- (Polestar, GPL-3.0). Do not edit: rerun the generator after a Polestar update.",
        "local _, B = ...",
        "",
        "-- uiMapID -> zone name (English, as Guidelime guides write them)",
        "B.ZONE_NAMES = {",
    ]
    lines += [f"\t[{i}] = {q(zones[i])}," for i in sorted(zones)]
    lines += ["}", "", "-- node, uiMapID, x, y (Era frame), faction mask (1 Alliance, 2 Horde), name", "B.TAXI = {"]
    lines += [f"\t{{ {t['node']}, {t['map']}, {t['x']}, {t['y']}, {t['mask']}, {q(t['name'])} }}," for t in taxi]
    lines += ["}", "", "-- area, uiMapID, x, y, frame (\"e\" Era), innkeeper npc, names...", "B.INNS = {"]
    for inn in inns:
        names = ", ".join(q(n) for n in inn["names"])
        lines.append(f"\t{{ {inn['area']}, {inn['map']}, {inn['x']}, {inn['y']}, {q(inn['frame'])}, {inn['npc']}, {names} }},")
    lines += ["}", ""]
    with open(OUT, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(lines))
    print(f"Polestar {version}: {len(zones)} zones, {len(taxi)} flight points, {len(inns)} inns -> {OUT}")


if __name__ == "__main__":
    main()
